#!/usr/bin/env python3
"""Generate portable plugin files and the self-contained Rovo prompt from one source.

Use --check in validation. Generated files are committed so clone/install works.
"""
import argparse
import json
from hashlib import sha256
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from skill_adapter.bundle import read_bundle


def outputs():
    bundle = read_bundle()
    target = ROOT / "skills/product-support-investigator"
    files = {target / name: data for name, data in bundle.items()}
    gate = (ROOT / "atlassian/compliance-gate.txt").read_bytes()
    adapter = (ROOT / "atlassian/rovo-adapter.txt").read_bytes()
    body = bundle["SKILL.md"].decode("utf-8").split("---\n", 2)[2].encode("utf-8")
    rovo_target = ROOT / "forge-app/skills/product-support-investigation"
    rovo_header = (ROOT / "atlassian/rovo-skill-header.txt").read_bytes()
    rovo_skill = (rovo_header + b"\n<!-- Generated from canonical sources; do not edit directly. -->\n\n"
                  + adapter + b"\n" + body)
    files[rovo_target / "SKILL.md"] = rovo_skill
    # Native rovo:skill supports bundled Markdown, not executable helpers.
    files.update({rovo_target / name: data for name, data in bundle.items()
                  if name != "SKILL.md" and name.endswith(".md")})
    # Manifest templates also serve the prompt without rovo:skill. Keep it
    # self-contained; moving a core section to a reference must not remove it here.
    prompt = gate + b"\n" + adapter + b"\nCanonical investigation instructions\n" + body
    for name, data in bundle.items():
        if name != "SKILL.md" and name.endswith(".md"):
            prompt += b"\n\nSupporting file: " + name.encode() + b"\n" + data
    # Discard Markdown hard-break spaces in the plain-text prompt.
    prompt = b"\n".join(line.rstrip()
                         for line in prompt.split(b"\n"))
    files[ROOT / "forge-app/prompts/investigator.md"] = prompt
    headings = bundle["references/reporting.md"].decode("utf-8").split(
        "For Standard investigations, use relevant sections from:\n\n", 1)[1].split(
        "\n\n", 1)[0]
    files[ROOT / "docs/OUTPUT_FORMAT.md"] = (
        "# Output Format\n\nGenerated by `scripts/sync_skill.py` from `references/reporting.md`; do not edit directly.\n\n"
        "This menu is optional. Use relevant sections; omit empty sections and mark useful unresolved fields Unknown.\n\n"
        + headings + "\n\nSee the canonical skill for evidence, hypothesis, confidence, and command requirements.\n"
    ).encode("utf-8")
    from observability.trace.evaluator import CHECKLIST
    files[ROOT / "forge-app/src/trace-contract.json"] = (json.dumps({
        "schema_version": "1.0", "skill_version": "sha256:" + sha256(bundle["SKILL.md"]).hexdigest(),
        "checks": CHECKLIST,
        "skill_bytes": len(rovo_skill),
        "instructions_bytes": len(prompt),
        "prompt_hash": "sha256:" + sha256(prompt).hexdigest(),
    }, indent=2) + "\n").encode()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        print("Generated skill files differ; run python3 scripts/sync_skill.py:", *stale, sep="\n")
        return 1
    print("Generated skill files verified" if args.check else "Generated skill files updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
